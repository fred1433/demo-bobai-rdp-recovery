#!/usr/bin/env python3
"""Collect every scenario result under runs/scenarios into trials/ (JSON + logs) and trials/RESULTS.md."""
import glob, json, os, shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "trials")
os.makedirs(OUT, exist_ok=True)

rows = []
for p in sorted(glob.glob(os.path.join(ROOT, "runs", "scenarios", "*.json"))):
    r = json.load(open(p))
    base = p[:-5]
    name = os.path.basename(base)
    for f in glob.glob(base + ".*"):
        shutil.copy(f, OUT)
    s = r.get("summary") or r.get("restart_summary") or {}
    saves = sum(1 for e in r["journal"] if e["event"] == "SAVE_CLICK_SENT")
    model = sum(1 for e in r["journal"] if e["event"] == "MODEL_CALL")
    ops = ", ".join(f"{k}={v}" for k, v in (s.get("operator_values") or {}).items()) or "none"
    st = f"{s.get('status')} {s.get('ref') or ''}"
    if r["scenario"] == "intent_crash_clear":
        rs = r["restart_summary"]
        st = f"restart: {rs['status']} {rs.get('ref') or ''}; after clear: {st}"
    rows.append(f"| `{name}` | {r['scenario']} | {st} | {saves} | "
                f"{r['host_check']['records_on_host']} | {model} | {ops} |")

with open(os.path.join(OUT, "RESULTS.md"), "w") as f:
    f.write("# Trial results (generated by scripts/results_table.py)\n\n"
            "Every row is one replay of `scripts/scenario.py`. *Save clicks* is counted in the client journal; "
            "*records on host* is the independent check read from the host's storage after the run "
            "(the executor never reads it). *Model calls* counts calls to the local vision model. "
            "Each replay starts from an empty host, which is why every saved record is R-10481. "
            "Operator actions and faults are played by the test harness (`scripts/scenario.py`); "
            "the executor runs as a separate process and is not told what will happen.\n\n"
            "| run | scenario | final status | Save clicks | records on host | model calls | operator values kept |\n"
            "|---|---|---|---|---|---|---|\n")
    f.write("\n".join(rows) + "\n")
print("\n".join(rows))
